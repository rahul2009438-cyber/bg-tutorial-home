/**
 * Extracts target word count if mentioned in brackets or text like [300 words], (২০০ শব্দ), etc.
 */
function extractTargetWordCount(input) {
  if (!input) return null;
  // Match patterns like [300 words], (250 শব্দ), 150 words, etc.
  const bengaliToEnglishDigits = (str) =>
    str.replace(/[০-৯]/g, d => '০১২৩৪৫৬৭৮৯'.indexOf(d));
  
  const normalized = bengaliToEnglishDigits(input);
  const match = normalized.match(/(?:\[|\(|\b)(\d{2,4})\s*(?:words?|শব্দ|শব্দে)(?:\]|\)|\b)/i);
  if (match) {
    return parseInt(match[1], 10);
  }
  return null;
}

/**
 * Strips bracketed word counts from title for clean searching
 */
function cleanTopicTitle(input) {
  if (!input) return '';
  return input
    .replace(/\[\s*\d+\s*(?:words?|শব্দ|শব্দে)?\s*\]/gi, '')
    .replace(/\(\s*\d+\s*(?:words?|শব্দ|শব্দে)?\s*\)/gi, '')
    .trim();
}

