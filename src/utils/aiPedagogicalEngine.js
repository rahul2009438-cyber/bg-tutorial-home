/**
 * Searches the Knowledge Base for matches
 */
function findInKnowledgeBase(query) {
  const cleanQ = cleanTopicTitle(query).toLowerCase();
  for (const key of Object.keys(ACADEMIC_KNOWLEDGE_BASE)) {
    const item = ACADEMIC_KNOWLEDGE_BASE[key];
    for (const alias of item.aliases) {
      if (cleanQ.includes(alias.toLowerCase())) {
        return item;
      }
    }
  }
  return null;
}

